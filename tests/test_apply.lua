local mock = require("wowmock")

test("Performance sets the normal CVars, the raid twins and raid overrides", function()
	local w = mock.new()
	w:login()
	w:slash("apply performance")
	eq(w:cvar("giQuality"), "1")
	eq(w:cvar("RAIDgiQuality"), "1")
	eq(w:cvar("useTargetFPS"), "0")
	eq(w:cvar("useMaxFPS"), "1")
	eq(w:cvar("maxFPS"), "60")
	eq(w:cvar("graphicsViewDistance"), "5")
	eq(w:cvar("raidGraphicsViewDistance"), "4")
	eq(w:cvar("graphicsGroundClutter"), "5")
	eq(w:cvar("raidGraphicsGroundClutter"), "3")
	eq(w:cvar("RAIDsunShafts"), "0")
	eq(w:cvar("RAIDWaterDetail"), "1")
	eq(w:cvar("uiScale"), "1", "UI scale is left to the game")
	eq(w:cvar("cameraDistanceMaxZoomFactor"), "2.6")
	eq(w.ns.DB.activePreset, "performance")
	eq(w.ns.PresetDrift("performance"), 0)
end)

test("Battery hits its 30 fps cap and render scale", function()
	local w = mock.new()
	w:login()
	w:slash("apply Battery")
	eq(w:cvar("maxFPS"), "30")
	eq(w:cvar("maxFPSBk"), "20")
	eq(w:cvar("RenderScale"), "0.85")
	eq(w:cvar("giQuality"), "1", "Fair: the lowest Options offers")
	eq(w:cvar("graphicsLightMode"), "0", "Options shows Fair")
	eq(w:cvar("raidGraphicsGroundClutter"), "1")
end)

test("index CVars are written before the raw CVars they rewrite", function()
	local w = mock.new()
	w:login()
	-- graphicsParticleDensity 2 makes the client set particleDensity 50; the preset wants 40
	w.ns.ApplyPreset("balanced")
	eq(w:cvar("graphicsParticleDensity"), "2")
	eq(w:cvar("particleDensity"), "40")
	local idx, raw
	for i, name in ipairs(w.store.sets) do
		if name == "graphicsParticleDensity" then idx = i end
		if name == "particleDensity" then raw = i end
	end
	ok(idx and raw and idx < raw, "graphicsParticleDensity must be written before particleDensity")
end)

test("unknown CVars are skipped and listed, the rest still applies", function()
	local w = mock.new({ missing = { "maxFPSLoading", "physicsLevel" } })
	w:login()
	w:slash("apply performance")
	eq(w:cvar("maxFPS"), "60")
	contains(w:chatText(), "skipped (unknown to this client): maxFPSLoading, physicsLevel")
	eq(#w.ns.DB.lastApply.skipped, 2)
end)

test("raid twins are left alone when raid sync is off", function()
	local w = mock.new()
	w:login()
	w:slash("raid off")
	w:slash("apply performance")
	eq(w:cvar("giQuality"), "1")
	eq(w:cvar("RAIDgiQuality"), "2")
	eq(w:cvar("raidGraphicsViewDistance"), "4")
end)

test("applying in combat waits for combat to end, last request wins", function()
	local w = mock.new()
	w:login()
	w:setCombat(true)
	w:slash("apply performance")
	w:slash("apply battery")
	eq(w:cvar("maxFPS"), "144", "nothing written in combat")
	contains(w:chatText(), "will apply when combat ends")
	w:setCombat(false)
	eq(w:cvar("maxFPS"), "30")
	eq(w.ns.DB.activePreset, "battery")
end)

test("preview lists changes first and does not write anything", function()
	local w = mock.new({ missing = { "physicsLevel" } })
	w:login()
	local rows = w.ns.PreviewPreset("performance")
	eq(rows[1].status, "change")
	eq(rows[#rows].status, "unknown")
	eq(#w.store.sets, 0)
end)

test("drift counts settings changed after a preset was applied", function()
	local w = mock.new()
	w:login()
	w.ns.ApplyPreset("performance")
	C_CVar.SetCVar("maxFPS", "90")
	eq(w.ns.PresetDrift("performance"), 1)
end)

test("unknown preset name is reported", function()
	local w = mock.new()
	w:login()
	w:slash("apply turbo")
	contains(w:chatText(), 'Unknown preset "turbo"')
	eq(#w.store.sets, 0)
end)
