	eq(w.reloads, 1)

end)

test("slash commands: help, unknown, status, fps, preview, reminder", function()
	local w = mock.new()
	w:login()
	w:slash("help")
	contains(w:chatText(), "/deckforever apply battery|balanced|performance|quality")
	ok(not w:chatText():find("/deckforever calibrate", 1, true), "testing tools are not in the help")
	w:clearChat()
	w:slash("bogus")
	contains(w:chatText(), 'Unknown command "bogus"')
	w:clearChat()
	w:slash("status")
	contains(w:chatText(), "Active preset: none")
	contains(w:chatText(), "Snapshot: none")
	w:clearChat()
	w:slash("fps")
	contains(w:chatText(), "60.0 fps, cap none")
	w:clearChat()
	w:slash("preview battery")
	contains(w:chatText(), "maxFPS: 144 -> 30")
	contains(w:chatText(), "would change")
	w:slash("reminder 45")
	eq(w.ns.DB.options.reminder, true)
	eq(w.ns.DB.options.reminderMinutes, 45)
	w:slash("reminder off")
	eq(w.ns.DB.options.reminder, false)
	w:clearChat()
	w:slash("raid maybe")
	contains(w:chatText(), "Usage: /deckforever raid on|off")
end)

