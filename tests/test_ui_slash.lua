test("window toggles, preset cards apply, footer Restore follows the snapshot", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w:slash("")
	local win = w:frame("DeckForeverWindow")
	local P = win.pages
	ok(win:IsShown())
	ok(P.presets:IsShown(), "opens on Presets")
	eq(win.restore.enabled, false)
	contains(win.status.text, "your own settings")
	contains(win.status.text, "60 fps")
	contains(P.presets.cards.battery.numbers[1].text, "Max FPS  30")

	P.presets.cards.battery.apply:Click()
	eq(w:cvar("maxFPS"), "30")
	eq(win.restore.enabled, true)
	contains(win.status.text, "Battery")
	ok(P.presets.cards.battery.badge:IsShown())
	ok(not P.presets.cards.performance.badge:IsShown())
	eq(P.presets.cards.battery.apply.text, "Re-apply")

	C_CVar.SetCVar("maxFPS", "50")
	w.ns.Changed()
	contains(win.status.text, "(1 changed since)")
	contains(P.presets.cards.battery.drift.text, "1 changed since applied")

	win.restore:Click()
	eq(w:cvar("maxFPS"), "144")
	eq(win.restore.enabled, false)

	w:slash("")
	ok(not win:IsShown())
	eq(#UISpecialFrames, 1)
end)

