test("UI scale falls back to scaling UIParent when the game locks its CVar", function()
	local w = mock.new({ locked = { "uiScale", "useUiScale" } })
	w:login()
	eq(rawget(w:frame("UIParent"), "scale"), nil, "untouched until the user picks a value")
	w:slash("uiscale 0.75")
	eq(w:frame("UIParent"):GetScale(), 0.75)
	contains(w:chatText(), "scaled by DeckForever")
	w:fire("UI_SCALE_CHANGED")
	eq(w:frame("UIParent"):GetScale(), 0.75, "re-applied when the game resets it")
	w:slash("uiscale default")
	eq(w.ns.DB.options.uiScale, nil)

	local w2 = mock.new()
	w2:login()
	w2:slash("uiscale 0.8")
	eq(w2:cvar("uiScale"), "0.8", "the CVar is used when the client allows it")
	eq(w2:cvar("useUiScale"), "1")
	eq(rawget(w2:frame("UIParent"), "scale"), nil)
	contains(w2:chatText(), "game setting")
	w2:slash("uiscale 2")
	contains(w2:chatText(), "Usage")
end)
