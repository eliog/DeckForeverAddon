local mock = require("wowmock")

local function FindButton(w, parent, text)
	for _, f in ipairs(w.frames) do
		if f.text == text and f.scripts.OnClick then return f end
	end
	error("no button " .. text)
end

test("first login on a Deck shows the prompt once, after a short delay", function()
	local w = mock.new()
	w:login()
	eq(w:frame("DeckForeverPrompt"), nil, "not before the delay")
	w:advance(3)
	local p = w:frame("DeckForeverPrompt")
	ok(p and p:IsShown())
	contains(p.preview.text, "settings will change")
	contains(p.preview.text, "giQuality: 2 -> 1")
	eq(w.ns.DB.promptedOnce, false, "shown is not answered")
	FindButton(w, p, "Not now"):Click()
	ok(w.ns.DB.promptedOnce)

	local w2 = mock.new({ savedVariables = DeckForeverDB })
	w2:login()
	w2:advance(10)
	eq(w2:frame("DeckForeverPrompt"), nil, "never re-prompted")
end)

test("prompt waits for the intro cinematic and Escape does not dismiss it", function()
	local w = mock.new()
	w:login()
	w.cinematic = true
	w:fire("CINEMATIC_START")
	w:advance(30)
	eq(w:frame("DeckForeverPrompt"), nil, "hidden during the cinematic")
	w.cinematic = false
	w:fire("CINEMATIC_STOP")
	w:advance(1)
	eq(w:frame("DeckForeverPrompt"), nil, "short pause after the cinematic")
	w:advance(1)
	local p = w:frame("DeckForeverPrompt")
	ok(p and p:IsShown())
	eq(#UISpecialFrames, 0, "Escape must not close the prompt")
	p:Hide() -- the close X
	ok(w.ns.DB.promptedOnce)
end)

test("no prompt off the Deck or on a /reload", function()
	local w = mock.new({ screen = { 1920, 1080 } })
