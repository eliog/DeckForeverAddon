test("window remembers its tab, position and size", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w.ns.ShowTab("options")
	local win = w:frame("DeckForeverWindow")
	ok(win.pages.options:IsShown())
	ok(not win.pages.presets:IsShown())
	win.GetPoint = function() return "TOPLEFT", UIParent, "TOPLEFT", 100, -50 end
	win.scripts.OnDragStop(win)
	win.pages.options.scale.next:Click()
	eq(w.ns.DB.options.window.scale, 1.3)
	w:slash("")

	local w2 = mock.new({ savedVariables = DeckForeverDB, screen = { 1920, 1080 } })
	w2:login()
	w2:slash("")
	ok(w2:frame("DeckForeverWindow").pages.options:IsShown(), "reopens on the last tab")
	eq(w2.ns.DB.options.window.point[3], 100)
end)

