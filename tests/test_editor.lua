local mock = require("wowmock")

local function RowFor(w, cvar)
	for _, f in ipairs(w.frames) do
		local s = rawget(f, "setting")
		if type(s) == "table" and s.cvar == cvar then return f end
	end
	error("no row for " .. cvar)
end

-- Overrides ---------------------------------------------------------------------------

test("an override changes what the preset applies, world and raid", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	ok(w.ns.SetOverride("battery", "maxFPS", 45))
	ok(w.ns.SetOverride("battery", "graphicsViewDistance", 6))
	w:slash("apply battery")
	eq(w:cvar("maxFPS"), "45")
	eq(w:cvar("graphicsViewDistance"), "6")
	eq(w:cvar("raidGraphicsViewDistance"), "6", "raid follows the override, not the preset's raid value")
	eq(w:cvar("maxFPSBk"), "20", "the rest of the preset is unchanged")
	ok(w.ns.HasOverrides("battery"))
	ok(not w.ns.HasOverrides("performance"))
end)

test("overriding an index CVar drops the raw CVars it owns", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w.ns.SetOverride("battery", "graphicsParticleDensity", 4)
	w:slash("apply battery")
	eq(w:cvar("graphicsParticleDensity"), "4")
	eq(w:cvar("particleDensity"), "100", "client-derived from level 4, not the preset's 20")
	eq(w:cvar("RAIDparticleDensity"), "50", "raid raw untouched (the mock only derives the world value)")
end)

test("overriding Secondary Lighting writes the matching giQuality", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w.ns.SetOverride("performance", "graphicsLightMode", 2)
	w:slash("apply performance")
	eq(w:cvar("graphicsLightMode"), "2")
	eq(w:cvar("giQuality"), "3")
	eq(w:cvar("RAIDgiQuality"), "3", "raid lighting kept matched")
end)

test("setting an override back to the preset value removes it", function()
	local w = mock.new()
	w:login()
	w.ns.SetOverride("battery", "maxFPS", 40)
	w.ns.SetOverride("battery", "maxFPS", 30)
	ok(not w.ns.HasOverrides("battery"))
	eq(w.ns.DB.overrides.battery, nil)
end)

test("overrides refuse unknown CVars, raid twins and out-of-range values", function()
	local w = mock.new()
	w:login()
	local good, why = w.ns.SetOverride("battery", "maxFPS", 500)
	ok(not good)
	contains(why, "above max")
	ok(not w.ns.SetOverride("battery", "notACVar", 1))
	ok(not w.ns.SetOverride("battery", "raidGraphicsViewDistance", 2))
	ok(not w.ns.HasOverrides("battery"))
end)

test("overrides survive a relog", function()
	local w = mock.new()
	w:login()
	w.ns.SetOverride("quality", "RenderScale", 0.99)
	local w2 = mock.new({ savedVariables = DeckForeverDB })
	w2:login()
	eq(w2.ns.EffectiveValue("quality", "RenderScale"), 0.99)
end)

-- Editor -----------------------------------------------------------------------------

test("editor steppers change overrides and show them", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w:slash("customize battery")
	local e = w:frame("DeckForeverWindow").pages.customize
	ok(e:IsShown())
	contains(e.summary.text, "Battery")
	contains(e.summary.text, "Built-in values")

	local row = RowFor(w, "maxFPS")
	eq(row.value.text, "30")
	row.next:Click()
	contains(row.value.text, "36")
	contains(row.value.text, "|cffffd100", "changed values are gold")
	ok(row.reset:IsShown())
	contains(e.summary.text, "1 customized")
	contains(e.presetButtons.battery.text, "Battery *")
	eq(w.ns.EffectiveValue("battery", "maxFPS"), 36)

	row.reset:Click()
	eq(row.value.text, "30")
	ok(not row.reset:IsShown())
	ok(not w.ns.HasOverrides("battery"))
end)

test("editor steppers stop at the ends and use level names", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w.ns.ShowEditor("battery")
	local row = RowFor(w, "graphicsLightMode")
	eq(row.value.text, "Fair")
	eq(row.prev.enabled, false, "Fair is the lowest")
	row.next:Click()
	row.next:Click()
	contains(row.value.text, "High")
	eq(row.next.enabled, false)
	contains(RowFor(w, "RenderScale").value.text, "85%")
	contains(RowFor(w, "graphicsLightMode").now.text, "now Good", "current client value shown")
end)

test("editor tabs switch presets; Apply and two-click reset work", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w.ns.ShowEditor("performance")
	local e = w:frame("DeckForeverWindow").pages.customize
	e.presetButtons.quality:Click()
	contains(e.summary.text, "Quality")
	RowFor(w, "maxFPS").next:Click()
	eq(w.ns.EffectiveValue("quality", "maxFPS"), 36)

	e.apply:Click()
	eq(w:cvar("maxFPS"), "36")
	eq(w.ns.DB.activePreset, "quality")

	e.resetAll:Click()
	ok(w.ns.HasOverrides("quality"), "first click only arms")
	contains(e.resetAll.text, "Click again")
	e.resetAll:Click()
	ok(not w.ns.HasOverrides("quality"))
	contains(e.status.text, "press Apply", "active preset now differs from the game")
end)

test("editor opens on the active preset by default", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w:slash("apply battery")
	w:slash("customize")
	contains(w:frame("DeckForeverWindow").pages.customize.summary.text, "Battery")
end)

-- Slash and panel ------------------------------------------------------------------------

test("slash set/reset manage overrides, case-insensitive CVar names", function()
	local w = mock.new()
	w:login()
	w:slash("set battery maxfps 45")
	eq(w.ns.EffectiveValue("battery", "maxFPS"), 45)
	contains(w:chatText(), "Battery: maxFPS = 45")
	w:slash("set battery maxFPS 999")
	contains(w:chatText(), "Not set: maxFPS above max")
	w:slash("set turbo maxFPS 45")
	contains(w:chatText(), "Usage: /deckforever set")
	w:slash("reset battery maxFPS")
	ok(not w.ns.HasOverrides("battery"))
	w:slash("set battery RenderScale 0.8")
	w:slash("set battery vsync 0")
	w:slash("reset battery")
	ok(not w.ns.HasOverrides("battery"))
end)

test("preset cards mark customized presets and jump to Customize and Steam Deck", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w.ns.SetOverride("battery", "maxFPS", 40)
	w:slash("")
	local win = w:frame("DeckForeverWindow")
	local cards = win.pages.presets.cards
	contains(cards.battery.title.text, "Battery")
	contains(cards.battery.title.text, "*")
	ok(not cards.performance.title.text:find("*", 1, true))
	contains(cards.battery.numbers[1].text, "40", "customized value shown on the card")
	contains(cards.battery.hours.text, "4.5 h questing")
	contains(cards.quality.hours.text, "2.6 h questing")
	cards.battery.edit:Click()
	ok(win.pages.customize:IsShown())
	contains(win.pages.customize.summary.text, "Battery")
	cards.quality.deck:Click()
	ok(win.pages.deck:IsShown())
	eq(win.pages.deck.presetHeader.text, "Max Quality")
	win.reload:Click()
	eq(w.reloads, 1)
end)

-- Steam Deck guide ------------------------------------------------------------------------

test("Steam Deck guide shows the active preset's Quick Access settings", function()
	local w = mock.new({ screen = { 1920, 1080 } })
	w:login()
	w:slash("apply battery")
	contains(w:chatText(), "Steam Deck (... > Performance): Refresh Rate 90 Hz, Framerate Limit Off or 30, TDP Limit 8-10 W.")
	w:slash("deck")
	local g = w:frame("DeckForeverWindow").pages.deck
	ok(g:IsShown())
	contains(g.presetButtons.battery.text, "Battery (active)")
	eq(g.presetRows[1].setting.text, "Refresh Rate")
	contains(g.presetRows[1].value.text, "90 Hz")
	contains(g.presetRows[1].why.text, "OLED")
	g.presetButtons.performance:Click()
	contains(g.presetRows[1].value.text, "60 Hz")
	eq(g.commonRows[1].setting.text, "Use per-game profile")
end)

